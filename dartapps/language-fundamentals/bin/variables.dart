void main() {
  //variable declration
  //syntax 1: type variableName=value
  int a = 10;
  double d = 10.5;
  print("int Type =" + a.toString());
  print("double Type " + d.toString());

  //syntax 2: var variableName=value
  var b = 20;
  var c = 20.5;
  print("int type Inference = " + b.toString());
  print("double type Inference = " + c.toString());
}
